-- ---------------------------------------------------------------------------
-- Audit.
-- ---------------------------------------------------------------------------
--
-- last_touched_at is excluded: it moves on every write by definition, and
-- without excluding it the "nothing a human changed" test in audit.log_change
-- would never fire and every touch would log a row.
create trigger z_audit_support_tickets
  after insert or delete or update on support.tickets
  for each row execute function audit.log_change('last_touched_at');

create trigger z_audit_support_events
  after insert or delete or update on support.events
  for each row execute function audit.log_change();

-- ---------------------------------------------------------------------------
-- RLS. ticket_team, manager, super_admin read and write; counsellor nothing;
-- anon nothing. The intake endpoint uses the service role, which bypasses RLS
-- and is gated by a shared secret in the route instead.
-- ---------------------------------------------------------------------------

alter table support.tickets         enable row level security;
alter table support.events          enable row level security;
alter table support.faculty_aliases enable row level security;

create policy tickets_support_all on support.tickets
  for all to authenticated using (app.is_support()) with check (app.is_support());

create policy events_support_all on support.events
  for all to authenticated using (app.is_support()) with check (app.is_support());

create policy aliases_support_read on support.faculty_aliases
  for select to authenticated using (app.is_support());

create policy aliases_admin_write on support.faculty_aliases
  for all to authenticated using (app.is_admin()) with check (app.is_admin());

-- PostgREST reaches a schema only if it is exposed and usable. The grants are
-- deliberately narrow: no anon, anywhere.
grant usage on schema support to authenticated, service_role;
grant select, insert, update on support.tickets to authenticated, service_role;
grant select, insert on support.events to authenticated, service_role;
grant select on support.faculty_aliases to authenticated, service_role;
grant insert, update, delete on support.faculty_aliases to authenticated, service_role;
grant usage, select on all sequences in schema support to authenticated, service_role;

revoke all on schema support from anon;

notify pgrst, 'reload schema';
